import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
const {chromium,expect}=await import(process.env.PLAYWRIGHT_MODULE??'playwright/test');
const url=process.env.DXFER_QA_URL??'http://127.0.0.1:5037';
assert.ok(['localhost','127.0.0.1','dxferdev.sync.harrisonmetals.com'].includes(new URL(url).hostname));
await mkdir('/tmp/dxfer-hotkey-search-evidence',{recursive:true});
const browser=await chromium.launch({headless:true});
try{
 const page=await browser.newPage({viewport:{width:1188,height:761},extraHTTPHeaders:{'X-DXFER-API-Key':process.env.DXFER_QA_API_KEY}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 const ready=()=>page.waitForFunction(()=>document.querySelector('input[type=file]')?._blazorInputFileNextFileId!==undefined);
 await page.goto(url);await ready();
 const build=await page.locator('.app-brand').getAttribute('title');
 if(process.env.DXFER_EXPECTED_REVISION)assert.ok(build.includes(process.env.DXFER_EXPECTED_REVISION),build);
 const tool=async name=>{await page.getByRole('button',{name,exact:true}).click();await page.waitForTimeout(200);};
 const open=async()=>{await tool('Open application menu');await tool('Hotkeys');};
 const search=page.getByRole('searchbox',{name:'Search hotkeys'}), panel=page.getByRole('region',{name:'Tool hotkey settings'});
 const line=page.getByRole('textbox',{name:'Line hotkey',exact:true});
 const canvas=page.locator('canvas.drawing-canvas');
 await open();await expect(search).toBeFocused();
 const all=await panel.locator('.dxfer-hotkey-row').count();assert.ok(all>20);
 await search.fill('line');await expect(line).toBeVisible();assert.ok(await panel.locator('.dxfer-hotkey-row').count()<all);
 await line.press('l');await expect(line).toHaveValue('L');
 await search.fill('CIRCLE');const circle=page.getByRole('textbox',{name:'Center circle hotkey',exact:true});await expect(circle).toBeVisible();
 await circle.press('l');await expect(page.getByRole('alert')).toContainText('already assigned');
 await expect(circle).toHaveValue('C');
 await circle.press('Alt+k');await expect(circle).toHaveValue('Alt+K');
 await search.fill('Alt+K');await expect(panel.locator('.dxfer-hotkey-row')).toHaveCount(1);await expect(circle).toBeVisible();
 await page.screenshot({path:'/tmp/dxfer-hotkey-search-evidence/filtered.png'});
 await search.fill('not-a-command-xxx');await expect(panel.getByRole('status')).toContainText('No matching commands');
 await search.fill('line');await expect(line).toHaveValue('L');
 await search.press('Escape');await expect(panel).not.toBeVisible();
 await canvas.focus();await page.keyboard.press('l');await expect(canvas).toHaveAttribute('data-active-tool','line');await page.keyboard.press('Escape');
 await page.keyboard.press('Alt+k');await expect(canvas).toHaveAttribute('data-active-tool','centercircle');await page.keyboard.press('Escape');
 await page.reload();await ready();await open();await expect(search).toHaveValue('');await expect(line).toHaveValue('L');await expect(circle).toHaveValue('Alt+K');
 await search.fill('center circle');await circle.press('Backspace');await expect(circle).toHaveValue('');
 await tool('Close tool hotkey settings');await tool('Tool hotkeys');await expect(search).toBeFocused();await expect(line).toHaveValue('L');
 await page.screenshot({path:'/tmp/dxfer-hotkey-search-evidence/all-commands.png'});
 const r=await panel.boundingBox();assert.ok(r.y+r.height<=761);
 assert.equal(await canvas.getAttribute('data-entity-count'),'0');
 await expect(canvas).toHaveAttribute('data-active-tool','select');
 assert.deepEqual(errors,[]);
 console.log('PASS hamburger and View entry, focused search/name/key/no-results, filtered stable assignment, duplicate refusal with accurate display, custom execution/reload, clear and Escape; drawing unchanged. Build:',build);
}finally{await browser.close();}
